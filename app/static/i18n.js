let currentLang = localStorage.getItem("framepilot_lang") || "ar";

function getLang() {
  return currentLang;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("framepilot_lang", lang);
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");
  updateDOMTranslations();
  document.dispatchEvent(new CustomEvent("framepilot:lang", { detail: lang }));   // pages redraw their own text
}

function t(key, vars = {}) {
  const dict = I18N[currentLang] || I18N.ar;
  let str = dict[key] || I18N.en[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}

function updateDOMTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    if (key) {
      el.setAttribute("placeholder", t(key));
    }
  });

  const toggleBtn = document.getElementById("langToggleBtn");
  if (toggleBtn) {
    toggleBtn.textContent = t("lang_toggle");
  }
}

function highlightActiveNav() {
  const p = window.location.pathname;
  document.querySelectorAll(".nav-menu a").forEach(a => {
    if (a.getAttribute("href") === p) {
      a.classList.add("active");
    } else {
      a.classList.remove("active");
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setLang(currentLang);
  highlightActiveNav();
  const toggleBtn = document.getElementById("langToggleBtn");
  if (toggleBtn) {
    toggleBtn.addEventListener("click", () => {
      setLang(currentLang === "ar" ? "en" : "ar");
    });
  }
});
